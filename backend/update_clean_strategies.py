async def main():
    print("=" * 60)
    print("🔄 מעדכן אסטרטגיות לגרסאות נקיות")
    print("=" * 60)
    
    async with AsyncSessionLocal() as session:
        updated_count = 0
        
        for slug, clean_prompt in CLEAN_STRATEGIES.items():
            # מציאת האסטרטגיה
            result = await session.execute(
                select(PostStrategy).where(PostStrategy.slug == slug)
            )
            strategy = result.scalar_one_or_none()
            
            if strategy:
                strategy.system_prompt = clean_prompt
                updated_count += 1
                print(f"✅ {strategy.name} ({slug}) - עודכן")
            else:
                print(f"⚠️ {slug} - לא נמצא")
        
        await session.commit()
        
        print(f"\n{'=' * 60}")
        print(f"✅ עודכנו {updated_count} אסטרטגיות בהצלחה!")
        print("=" * 60)


if __name__ == "__main__":
    asyncio.run(main())
