async def update_strategies():
    """עדכון כל האסטרטגיות עם פרומפטים מקיפים"""
    async with AsyncSessionLocal() as session:
        updated_count = 0
        
        for slug, rich_prompt in RICH_STRATEGIES.items():
            # מציאת האסטרטגיה לפי slug
            result = await session.execute(
                select(PostStrategy).where(PostStrategy.slug == slug)
            )
            strategy = result.scalar_one_or_none()
            
            if strategy:
                print(f"📝 Updating: {strategy.icon} {strategy.name} ({slug})")
                strategy.system_prompt = rich_prompt
                updated_count += 1
            else:
                print(f"⚠️  Strategy not found: {slug}")
        
        await session.commit()
        print(f"\n✅ Done! Updated {updated_count} strategies with rich prompts.")


async def show_strategies():
    """הצגת כל האסטרטגיות"""
    async with AsyncSessionLocal() as session:
        result = await session.execute(
            select(PostStrategy).order_by(PostStrategy.sort_order)
        )
        strategies = result.scalars().all()
        
        print("\n📋 Current Strategies:")
        print("=" * 60)
        for s in strategies:
            status = "✅" if s.is_active else "❌"
            prompt_len = len(s.system_prompt) if s.system_prompt else 0
            print(f"{status} {s.icon} {s.name} ({s.slug}) - prompt: {prompt_len} chars")
        print("=" * 60)
        print(f"Total: {len(strategies)} strategies")


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="Update strategies with rich prompts")
    parser.add_argument("--show", action="store_true", help="Show current strategies")
    args = parser.parse_args()
    
    if args.show:
        asyncio.run(show_strategies())
    else:
        asyncio.run(update_strategies())
