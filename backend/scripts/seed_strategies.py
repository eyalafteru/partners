async def seed_strategies():
    """יצירת או עדכון האסטרטגיות בדאטאבייס"""
    async with AsyncSessionLocal() as session:
        for strategy_data in VIRAL_STRATEGIES:
            # בדיקה אם האסטרטגיה קיימת
            result = await session.execute(
                select(PostStrategy).where(PostStrategy.slug == strategy_data["slug"])
            )
            existing = result.scalar_one_or_none()
            
            if existing:
                # עדכון
                print(f"📝 Updating: {strategy_data['name']}")
                for key, value in strategy_data.items():
                    setattr(existing, key, value)
            else:
                # יצירה
                print(f"✨ Creating: {strategy_data['name']}")
                strategy = PostStrategy(**strategy_data)
                session.add(strategy)
        
        await session.commit()
        print(f"\n✅ Done! {len(VIRAL_STRATEGIES)} strategies seeded.")


async def list_strategies():
    """הצגת כל האסטרטגיות"""
    async with AsyncSessionLocal() as session:
        result = await session.execute(
            select(PostStrategy).order_by(PostStrategy.sort_order)
        )
        strategies = result.scalars().all()
        
        print("\n📋 Current Strategies:")
        print("-" * 60)
        for s in strategies:
            status = "✅" if s.is_active else "❌"
            print(f"{status} {s.icon} {s.name} ({s.slug}) - used {s.times_used}x")
        print("-" * 60)
        print(f"Total: {len(strategies)} strategies")


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="Seed viral post strategies")
    parser.add_argument("--list", action="store_true", help="List existing strategies")
    args = parser.parse_args()
    
    if args.list:
        asyncio.run(list_strategies())
    else:
        asyncio.run(seed_strategies())
